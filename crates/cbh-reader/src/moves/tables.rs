/// The byte a standard record would hold for a byte `raw` of a record in
/// `order` after `processed` moves: the byte gives a move kind, the
/// counter is taken from the kind, and the standard byte of that kind is
/// read as usual (with no further counter).
pub fn remapped_token(order: Order, raw: u8, processed: u8) -> u8 {
    static INVERSES: std::sync::OnceLock<[[u8; 256]; 2]> = std::sync::OnceLock::new();
    let inverses = INVERSES.get_or_init(|| {
        let mut inv = [[0u8; 256]; 2];
        for (t, table) in [&CHESS960_ORDER, &KIND4_ORDER].into_iter().enumerate() {
            for (i, &b) in table.iter().enumerate() {
                inv[t][b as usize] = i as u8;
            }
        }
        inv
    });
    let inverse = &inverses[order as usize];
    STANDARD_ORDER[inverse[raw as usize].wrapping_sub(processed) as usize]
}

